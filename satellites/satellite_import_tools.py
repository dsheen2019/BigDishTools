    def create_sat_data_dictionary_from_csv(self, csv_path, include_constellations=None, exclude_constellations=None):
        """
        take a path to a csv of sat ephemeris and produce a dictionary with earthsatellite objects and their original defining data
            
            data stored in the dictionary includes:  
                OBJECT_NAME,
                OBJECT_ID,
                EPOCH,
                MEAN_MOTION,
                ECCENTRICITY,
                INCLINATION,
                RA_OF_ASC_NODE,
                ARG_OF_PERICENTER,
                MEAN_ANOMALY,
                EPHEMERIS_TYPE,
                CLASSIFICATION_TYPE,
                NORAD_CAT_ID,
                ELEMENT_SET_NO,
                REV_AT_EPOCH,
                BSTAR,
                MEAN_MOTION_DOT,
                MEAN_MOTION_DDOT

        """

        sats = {}
        with open(csv_path, 'r') as f:
            for fields in omm.parse_csv(f):
                sat = Satrec()
                omm.initialize(sat, fields)
                e = EarthSatellite.from_satrec(sat, self.ts)
                e.name = fields.get('OBJECT_NAME')

                dict_data = {
                    "OBJECT_NAME" :         fields.get('OBJECT_NAME'),
                    "OBJECT_ID" :           fields.get('OBJECT_ID'),
                    "EPOCH" :               fields.get('EPOCH'),
                    "MEAN_MOTION" :         fields.get('MEAN_MOTION'),
                    "ECCENTRICITY" :        fields.get('ECCENTRICITY'),
                    "INCLINATION" :         fields.get('INCLINATION'),
                    "RA_OF_ASC_NODE":       fields.get('RA_OF_ASC_NODE'),
                    "ARG_OF_PERICENTER":    fields.get('ARG_OF_PERICENTER'),
                    "MEAN_ANOMALY":         fields.get('MEAN_ANOMALY'),
                    "EPHEMERIS_TYPE":       fields.get('EPHEMERIS_TYPE'),
                    "CLASSIFICATION_TYPE":  fields.get('CLASSIFICATION_TYPE'),
                    "NORAD_CAT_ID":         fields.get('NORAD_CAT_ID'),
                    "ELEMENT_SET_NO":       fields.get('ELEMENT_SET_NO'),
                    "REV_AT_EPOCH":         fields.get('REV_AT_EPOCH'),
                    "BSTAR":                fields.get('BSTAR'),
                    "MEAN_MOTION_DOT":      fields.get('MEAN_MOTION_DOT'),
                    "MEAN_MOTION_DDOT" :    fields.get('MEAN_MOTION_DDOT'),
                }

                try:
                    sats[e.name].append([e,dict_data])
                except:
                    sats[e.name] = [[e,dict_data]]

        return sats

    def create_timescale_times(self, start, stop, num_points):
        """
        Generate an array of timescale times from datetime bounds and number of points and return
        """

        timestamps = np.linspace(start.timestamp(), stop.timestamp(), num_points)
        #timescale_times = np.array([self.ts.from_datetime(datetime.fromtimestamp(timestamp, tz=timezone.utc)) for timestamp in timestamps])
        timescale_times = self.ts.from_datetimes([datetime.fromtimestamp(timestamp, tz=timezone.utc) for timestamp in timestamps])

        return timescale_times


    def convert_to_timescale(self, times):
        """
        take an array of datetimes and convert to timescale for calculations
        """
        timescale_times = [self.ts.from_datetime(dt) for dt in times]

        return timescale_times

