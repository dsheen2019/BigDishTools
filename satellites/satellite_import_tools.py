    def get_satellite_track(self, times, satellite, antenna_coord_object):
        """
        compute linearly interpolated sat trajectory using multiple epochs of ephemeris data
        times should be an array of timescale times
        satellite should be the dictionary entry for the specific satellite 
        antenna_coord_object should be a wgs84 object
        returns an array of az,el coordinates, ranges, and their derivatives as azels, azelrates, ranges, range_rates
        """

        ts = self.ts

        start_time = times[0]
        stop_time = times[-1]

        #timescale_times = np.array([self.ts.from_datetime(datetime.fromtimestamp(timestamp, tz=timezone.utc)) for timestamp in timestamps])


        ephemeris_epochs = np.array([sat[0].epoch for sat in satellite])

        #get nearest epoch

        if len(ephemeris_epochs) > 1:

            order = np.argsort(ephemeris_epochs)

            ordered_satellite = [satellite[i] for i in order]
            ordered_epochs= ephemeris_epochs[order]

            #determine which epochs we should calculate over

            leading_index = []
            trailing_index = []

            for t in times:
                try:
                    i1 = np.where(ordered_epochs<t)[0][-1]
                    i2 = np.where(ordered_epochs>t)[0][0]
                    leading_index.append(i1)
                    trailing_index.append(i2)
                except:
                    closest = np.argmin(np.abs(ordered_epochs-t))
                    leading_index.append(closest)
                    trailing_index.append(closest)

            ephemeris_calc_indices = np.unique(np.array([leading_index,trailing_index]))
            all_times = np.array([ordered_epochs[leading_index],times,ordered_epochs[trailing_index]]).swapaxes(0,1)

            diff_telescope = []

            for i in range(len(ephemeris_epochs)):
                #only compute for indices we use but allocate unused ones so as not to shift indexing
                if i in ephemeris_calc_indices:
                    diff_telescope.append(ordered_satellite[i][0] - antenna_coord_object)
                else:
                    diff_telescope.append([])

        else:

            diff_telescope = satellite[0][0] - antenna_coord_object


        #calculate for each included epoch

        azels = []
        azelrates = []
        ranges = []
        range_rates = []



        if len(ephemeris_epochs) > 1:

            alt = [] 
            az = []
            the_range = [] 
            altrate = [] 
            azrate = []
            range_rate = []

            for i in range(len(ephemeris_epochs)):
                #only compute for indices we use but allocate unused ones so as not to shift indexing
                if i in ephemeris_calc_indices:

                    alt1, az1, the_range1, altrate1, azrate1, range_rate1 = diff_telescope[i].at(times).frame_latlon_and_rates(antenna_coord_object)

                    #diff_data.append([alt, az, the_range, altrate, azrate, range_rate])
                    alt.append(alt1.degrees)
                    az.append(az1.degrees)
                    the_range.append(the_range1.m)
                    altrate.append(altrate1.degrees.per_second)
                    azrate.append(azrate1.degrees.per_second)
                    range_rate.append(range_rate1.m_per_s)

                else:
                    alt.append([])
                    az.append([])
                    the_range.append([])
                    altrate.append([])
                    azrate.append([])
                    range_rate.append([])


            for i in range(len(times)):
                t1, t2, t3 = all_times[i]

                if t3 - t1 > 0: #we actually have two independednt ephemeris sets to calculate with
                    
                    w1 = (t3-t2)/(t3-t1)
                    w3 = (t2-t1)/(t3-t1)

                    #alt1, az1, the_range1, altrate1, azrate1, range_rate1 = diff_data[leading_index[i]][i]#.frame_latlon_and_rates(antenna_coord_object)
                    #alt3, az3, the_range3, altrate3, azrate3, range_rate3 = diff_data[trailing_index[i]][i]#.frame_latlon_and_rates(antenna_coord_object)

                    li = leading_index[i]
                    ti = trailing_index[i]

                    alt1, az1, the_range1, altrate1, azrate1, range_rate1 = alt[li][i], az[li][i], the_range[li][i], altrate[li][i], azrate[li][i], range_rate[li][i]
                    alt3, az3, the_range3, altrate3, azrate3, range_rate3 = alt[ti][i], az[ti][i], the_range[ti][i], altrate[ti][i], azrate[ti][i], range_rate[ti][i]


                    azels.append([
                        (np.angle(w1 * np.exp(1j * np.radians(az1)) + w3 * np.exp(1j * np.radians(az3))) * 180 / np.pi)%360, #need to do this this way to dodge wraparound
                        w1 * alt1 + w3 * alt3
                        ]) 

                    azelrates.append([
                        w1 * azrate1 + w3 * azrate3,
                        w1 * altrate1 + w3 * altrate3,
                        ])
                    
                    ranges.append(w1 * the_range1 + w3 * the_range3)
                    
                    range_rates.append(w1 * range_rate1 + w3 * range_rate3)

                else: # clearly in this case we can only usefully run one calculation
                    #diff_t1 = diff_telescope[leading_index[i]].at(t2)
                    #alt1, az1, the_range1, altrate1, azrate1, range_rate1 = diff_data[leading_index[i]][i]#.frame_latlon_and_rates(antenna_coord_object) 
                    li = leading_index[i]
                    alt1, az1, the_range1, altrate1, azrate1, range_rate1 = alt[li][i], az[li][i], the_range[li][i], altrate[li][i], azrate[li][i], range_rate[li][i]
                    #diff_t1.frame_latlon_and_rates(antenna_coord_object)

                    azels.append([az1, alt1])
                    azelrates.append([azrate1, altrate1])
                    ranges.append(the_range1)
                    range_rates.append(range_rate1)

            azels = np.array(azels)
            azelrates = np.array(azelrates)
            ranges = np.array(ranges)
            range_rates = np.array(range_rates)


        else:

            diff_t1 = diff_telescope.at(times)
            alt1, az1, the_range1, altrate1, azrate1, range_rate1 = diff_t1.frame_latlon_and_rates(antenna_coord_object)

            azels = np.array([az1.degrees, alt1.degrees]).transpose()
            azelrates=np.array([azrate1.degrees.per_second, altrate1.degrees.per_second]).transpose()
            ranges = np.array(the_range1.m)
            range_rates = np.array(range_rate1.m_per_s)
                
        return azels, azelrates, ranges, range_rates

